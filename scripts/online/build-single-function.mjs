#!/usr/bin/env node
// Build a one-file `touchline-e{ENGINE_VERSION}` for the Supabase Dashboard (Edge Functions > Deploy a new function >
// Via editor), for when neither the CLI nor the connector can deploy: supabase/functions/touchline/index.ts with the
// verifier (src/online/server/entry.ts and everything it pulls in) bundled into the same file, and the two Supabase
// packages imported by inline `npm:` specifiers at the versions deno.json pins, so no deno.json or lock is needed.
//
//   node scripts/online/build-single-function.mjs [outfile]
//     default outfile: supabase/functions/touchline-e{V}-single/index.ts (gitignored, like the staged function)
//
// The output is compiled JavaScript in a .ts file (the editor's file name), marked `// @ts-nocheck`: the adapter is
// type-checked in the repository (`deno check supabase/functions/touchline/index.ts`), not in this generated copy.
// It holds no key: the platform injects SUPABASE_URL, the keys and the JWKS. Deploy with "Verify JWT" on.
import { build } from 'esbuild'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { forbiddenIn } from './build-verifier.mjs'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..')
const source = path.join(root, 'supabase', 'functions', 'touchline')
const engine = /export const ENGINE_VERSION\s*=\s*'([^']+)'/.exec(readFileSync(path.join(root, 'src/engine/version.ts'), 'utf8'))?.[1]
if (!engine) throw new Error('ENGINE_VERSION not found')
const imports = JSON.parse(readFileSync(path.join(source, 'deno.json'), 'utf8')).imports
const outfile = path.resolve(process.argv[2] ?? path.join(root, 'supabase', 'functions', `touchline-e${engine}-single`, 'index.ts'))

const inline = {
  name: 'touchline-single',
  setup(b) {
    // The verifier from source, exactly as build-verifier.mjs bundles it
    b.onResolve({ filter: /\/_shared\/verifier\.js$/ }, () => ({ path: path.join(root, 'src/online/server/entry.ts') }))
    // Bare Supabase imports become the npm: specifiers deno.json maps them to
    b.onResolve({ filter: /^@supabase\// }, (a) => {
      const spec = imports[a.path]
      if (!spec) throw new Error(`deno.json has no import for ${a.path}`)
      return { path: spec, external: true }
    })
  },
}

const result = await build({
  entryPoints: [path.join(source, 'index.ts')],
  bundle: true,
  write: false,
  platform: 'neutral',
  format: 'esm',
  target: 'es2022',
  tsconfig: path.join(root, 'tsconfig.app.json'),
  mainFields: ['module', 'main'],
  define: { 'import.meta.env.BASE_URL': '"/"', 'import.meta.env.PROD': 'true', 'import.meta.env.DEV': 'false' },
  legalComments: 'none',
  minify: true,
  plugins: [inline],
  logLevel: 'warning',
})
const code = result.outputFiles[0].text
const bad = forbiddenIn(code)
if (bad.length) throw new Error(`The function uses ${bad.join(', ')}: the server cannot run browser or Node code`)
if (/sb_secret_[A-Za-z0-9_-]{8}|eyJ[A-Za-z0-9_-]{10,}\./.test(code)) throw new Error('A key-shaped string ended up in the function')
const header = [
  '// @ts-nocheck',
  `// TouchLine Edge Function touchline-e${engine}, one file for the Supabase Dashboard editor. Verify JWT: ON.`,
  '// Generated by scripts/online/build-single-function.mjs from supabase/functions/touchline/index.ts and the',
  '// verifier (src/online/server); do not edit. No key is in this file: the platform injects them.',
  // With no lock file, this pins the supabase-js that @supabase/server resolves to the version deno.json pins
  `import '${imports['@supabase/supabase-js']}'`,
  '',
].join('\n')
mkdirSync(path.dirname(outfile), { recursive: true })
writeFileSync(outfile, header + code)
console.log(`touchline-e${engine} single file: ${path.relative(root, outfile) || outfile}, ${(Buffer.byteLength(header + code) / 1024).toFixed(0)} KB`)
