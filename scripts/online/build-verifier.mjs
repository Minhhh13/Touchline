#!/usr/bin/env node
// Build the verifier bundle the Edge Function imports: src/online/server/entry.ts and everything it pulls in from
// src/engine, src/game and src/online, as one ES module for Deno, into supabase/functions/_shared/verifier.js
// (generated, gitignored). Fails when the bundle names a DOM or Node global: the server must replay with the game's
// own code and nothing that only exists in a browser.
//
//   npm run build:verifier            minified (what is deployed)
//   node scripts/online/build-verifier.mjs --pretty   readable, for debugging
import { build } from 'esbuild'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..')
export const BUNDLE = path.join(root, 'supabase', 'functions', '_shared', 'verifier.js')

/** Globals that exist only in a browser or in Node. `crypto`, `TextEncoder`, `structuredClone` exist in Deno. */
export const FORBIDDEN = ['window.', 'document.', 'localStorage', 'sessionStorage', 'process.', 'require(', 'navigator.']

export function forbiddenIn(code) {
  return FORBIDDEN.filter((g) => code.includes(g))
}

export async function buildVerifier({ minify = true, outfile = BUNDLE } = {}) {
  mkdirSync(path.dirname(outfile), { recursive: true })
  const engine = /export const ENGINE_VERSION\s*=\s*'([^']+)'/.exec(readFileSync(path.join(root, 'src/engine/version.ts'), 'utf8'))?.[1]
  await build({
    entryPoints: [path.join(root, 'src/online/server/entry.ts')],
    bundle: true,
    platform: 'neutral',
    format: 'esm',
    target: 'es2022',
    tsconfig: path.join(root, 'tsconfig.app.json'),
    mainFields: ['module', 'main'],
    define: { 'import.meta.env.BASE_URL': '"/"', 'import.meta.env.PROD': 'true', 'import.meta.env.DEV': 'false' },
    legalComments: 'none',
    minify,
    outfile,
    banner: { js: `// TouchLine verifier bundle, engine ${engine}. Generated by scripts/online/build-verifier.mjs; do not edit.` },
    logLevel: 'warning',
  })
  const code = readFileSync(outfile, 'utf8')
  const bad = forbiddenIn(code)
  if (bad.length) throw new Error(`The verifier bundle uses ${bad.join(', ')}: the server cannot run browser or Node code`)
  return { outfile, bytes: Buffer.byteLength(code), engine }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const pretty = process.argv.includes('--pretty')
  buildVerifier({ minify: !pretty })
    .then(({ outfile, bytes, engine }) => {
      console.log(`verifier bundle (engine ${engine}): ${path.relative(root, outfile)}, ${(bytes / 1024).toFixed(0)} KB`)
    })
    .catch((e) => {
      console.error(e instanceof Error ? e.message : e)
      process.exit(1)
    })
}
