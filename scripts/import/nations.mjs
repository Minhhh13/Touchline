const BY_NAME = new Map()
for (const [name, code, flag] of TABLE) BY_NAME.set(name.toLowerCase(), { code, flag })
const BY_CODE = new Map()
for (const [, code, flag] of TABLE) if (!BY_CODE.has(code)) BY_CODE.set(code, flag)

export function nation(name) {
  if (!name) return { code: 'UNK', flag: '🏳️' }
  const hit = BY_NAME.get(String(name).trim().toLowerCase())
  if (hit) return hit
  return { code: 'UNK', flag: '🏳️', unknownName: name }
}

export function nationFlag(code) {
  return BY_CODE.get(code) ?? '🏳️'
}

export const NATION_NAMES = Object.fromEntries(TABLE.map(([name, code]) => [code, name]).reverse())
